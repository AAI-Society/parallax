#!/usr/bin/env bash
# Regenerate every number the paper cites. CI runs this and fails on a diff,
# so a stale figure cannot outlive a code change.
set -euo pipefail
cd "$(dirname "$0")/.."
cargo build --release --quiet
BIN=./target/release/parallax
mkdir -p results

for s in sigma1-software sigma2-tdx sigma3-quorum sigma4-zk sigma5-hybrid; do
  "$BIN" solve "examples/$s.toml" --format json > "results/$s.manifest.json"
done

# `compare` refuses two deployments that attest different claims (exit 2),
# because "which trust set is smaller" isn't meaningful across two different
# propositions. Of sigma{1,2,3,4}, only sigma1/sigma3 (both
# measurement_valid) and sigma2/sigma4 (both execution_valid) share a claim;
# the other eight ordered pairs would abort this script under `set -e` (or,
# for pairs whose output happens to fit in one pipe write, print a blank
# third column instead of failing loudly — see `require_same_claim` in
# `src/bin/parallax.rs`). Rather than silently truncating the matrix or
# aligning the examples' claims (which would erase the point of having two
# different claims across the four single-mechanism deployments), each
# mismatched pair gets an explicit "N/A" row naming why it was skipped, so
# the matrix stays complete and the omission is legible on its face.
#
# Looked up straight from each TOML file rather than a `declare -A` table:
# associative arrays need bash 4+, and macOS ships bash 3.2 by default, so a
# hardcoded table would pass in CI (Ubuntu) and fail silently-then-loudly on
# a contributor's Mac.
#
# The pipeline is guarded because `grep | cut` exits 0 on no match: `grep`'s
# exit 1 is swallowed by the pipe, `cut` reads nothing and succeeds, and
# `claim_of` returns the empty string. An example whose `claim` line was
# renamed or removed would then compare equal to any *other* such example
# (`"" = ""`), and the matrix would quietly report a real comparison for a
# pair the script never actually looked up. `set -euo pipefail` does not
# catch this on its own, because with an empty result there is nothing to
# fail on — hence the explicit emptiness check at the call sites below.
claim_of() {
  grep -m1 '^claim' "examples/$1.toml" | cut -d'"' -f2
}

# Fails loudly with the file named, rather than letting an empty claim
# propagate into the matrix as a comparison that was never made.
require_claim() {
  if [ -z "$2" ]; then
    echo "regen-results.sh: examples/$1.toml has no parseable \`claim\` line" >&2
    exit 1
  fi
}

# The paper `\input`s a generated `tabular` rather than a hand-copied table,
# so a number in the PDF cannot drift from the code that produced it. Only
# `_` needs escaping here: deployment names are `[a-z0-9-]` and claim names
# are snake_case identifiers, so no other LaTeX special character can reach
# a cell. `validate` rejects the reserved characters that would break the
# canonical mechanism grammar, but it does not police LaTeX syntax — if the
# example set ever grows a name containing `&`, `%`, `#`, `$`, `{`, `}`,
# `~` or `^`, extend this function rather than discovering it as a build
# failure in `paper/`.
tex_escape() {
  printf '%s' "$1" | sed 's/_/\\_/g'
}

: > results/comparison-matrix.txt
: > results/comparison-matrix.tex

{
  echo "# Pairwise comparison of residual trust sets"
  echo
  echo "'N/A' rows are pairs that attest different claims; \`parallax compare\`"
  echo "refuses to rank verifiability across two different propositions."
  echo
} >> results/comparison-matrix.txt

{
  echo "% Generated by scripts/regen-results.sh — do not edit."
  echo "% A bare tabular: the caption and float live in paper/main.tex."
  echo '\begin{tabular}{@{}ll>{\raggedright\arraybackslash}p{6.6cm}@{}}'
  echo '\toprule'
  echo 'Deployment A & Deployment B & Relation under set inclusion \\'
  echo '\midrule'
} >> results/comparison-matrix.tex

for a in sigma1-software sigma2-tdx sigma3-quorum sigma4-zk; do
  for b in sigma1-software sigma2-tdx sigma3-quorum sigma4-zk; do
    [ "$a" = "$b" ] && continue
    claim_a="$(claim_of "$a")"
    claim_b="$(claim_of "$b")"
    require_claim "$a" "$claim_a"
    require_claim "$b" "$claim_b"
    if [ "$claim_a" != "$claim_b" ]; then
      result="N/A (different claims: $claim_a vs $claim_b)"
      cell="N/A --- different claims (\\texttt{$(tex_escape "$claim_a")} vs \\texttt{$(tex_escape "$claim_b")})"
    else
      result="$("$BIN" compare "examples/$a.toml" "examples/$b.toml" | head -1)"
      cell="$(tex_escape "$result")"
    fi
    printf '%-18s %-18s %s\n' "$a" "$b" "$result" \
      >> results/comparison-matrix.txt
    printf '\\texttt{%s} & \\texttt{%s} & %s \\\\\n' \
      "$(tex_escape "$a")" "$(tex_escape "$b")" "$cell" \
      >> results/comparison-matrix.tex
  done
done

{
  echo '\bottomrule'
  echo '\end{tabular}'
} >> results/comparison-matrix.tex

"$BIN" solve examples/sigma5-hybrid.toml --shared > results/hybrid-shared-dependencies.txt

# The Sigma_2 trust set as the tool prints it, for the paper to set beside its
# hand-derived TDX table. Generated rather than transcribed for the same
# reason as everything else here: the whole claim of that subsection is that
# the two agree, and a transcribed table can agree with nothing but the
# typist.
"$BIN" solve examples/sigma2-tdx.toml --format latex > results/sigma2-trust-set.tex

# The candidate-ordering experiment. Run over the four single-mechanism
# deployments -- the same four the comparison matrix above ranks. Sigma_5 is
# excluded here on purpose: it is a hybrid built to carry a shared dependency,
# not a fifth design competing for a rung, and the matrix does not rank it
# either. It does appear in the per-deployment summary below, which is a
# statement of facts about each deployment rather than a ranking.
TIER_SET="examples/sigma1-software.toml examples/sigma2-tdx.toml \
examples/sigma3-quorum.toml examples/sigma4-zk.toml"
# shellcheck disable=SC2086  # word splitting is the point: these are argv
"$BIN" tiers $TIER_SET > results/tier-orderings.txt
# shellcheck disable=SC2086
"$BIN" tiers --format tex-orderings $TIER_SET > results/tier-orderings.tex

"$BIN" tiers --format tex-summary \
  examples/sigma1-software.toml examples/sigma2-tdx.toml \
  examples/sigma3-quorum.toml examples/sigma4-zk.toml \
  examples/sigma5-hybrid.toml > results/deployment-summary.tex

# Each manifest against the strict policy of `examples/policy-strict.toml`
# (no undetectable assumptions, nothing slower than 24h). `check` exits 1 on
# violations and 2 on a malformed input, so `|| true` would swallow the
# difference between "this deployment violates the policy" -- the expected,
# interesting outcome -- and "the tool broke". The exit code is captured and
# branched on instead, and anything other than 0 or 1 aborts the script.
: > results/policy-checks.txt
: > results/policy-checks.tex
{
  echo "# Each manifest against examples/policy-strict.toml"
  echo
  echo "forbid_undetectable = true, max_detection_latency = 24h."
  echo "Every deployment fails, and the count is the number of assumptions"
  echo "the strict policy objects to."
  echo
} >> results/policy-checks.txt
{
  echo "% Generated by scripts/regen-results.sh — do not edit."
  echo "% A bare tabular: the caption and float live in paper/main.tex."
  echo '\begin{tabular}{@{}llr@{}}'
  echo '\toprule'
  echo 'Deployment & Verdict & Violations \\'
  echo '\midrule'
} >> results/policy-checks.tex

for s in sigma1-software sigma2-tdx sigma3-quorum sigma4-zk sigma5-hybrid; do
  set +e
  out="$("$BIN" check "results/$s.manifest.json" \
        --policy examples/policy-strict.toml 2>&1)"
  code=$?
  set -e
  case "$code" in
    0) verdict="satisfies the policy" ; n=0 ;;
    1) verdict="violates the policy"
       n="$(printf '%s\n' "$out" | grep -c '^VIOLATION:')" ;;
    *) echo "regen-results.sh: \`check $s\` exited $code, not 0 or 1:" >&2
       printf '%s\n' "$out" >&2
       exit 1 ;;
  esac
  printf '%-34s %-22s %s violation(s)\n' "$s" "$verdict" "$n" \
    >> results/policy-checks.txt
  printf '\\texttt{%s} & %s & %s \\\\\n' \
    "$(tex_escape "$s")" "$verdict" "$n" >> results/policy-checks.tex
done

{
  echo '\bottomrule'
  echo '\end{tabular}'
} >> results/policy-checks.tex

echo "wrote results/"
